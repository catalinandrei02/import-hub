// Builds the Chrome extension: extension/reader.js from src/lib/listingReader.ts (the same code as the bookmark),
// then public/import-hub-extension.zip so family members can download it from the site.
// Run with: npm run build:ext
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const { readListing } = await import(path.join(root, "src/lib/listingReader.ts"));
const out = "// Generated by scripts/build-ext.mjs from src/lib/listingReader.ts. Do not edit.\n// Runs in the listing tab; its value is what the extension sends back.\n(" + readListing.toString() + ")();\n";
fs.writeFileSync(path.join(root, "extension/reader.js"), out);
// Zip it as a folder named "import-hub-extension" (what people see after unzipping).
const zip = path.join(root, "public/import-hub-extension.zip");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ihx-"));
fs.cpSync(path.join(root, "extension"), path.join(tmp, "import-hub-extension"), { recursive: true });
fs.rmSync(zip, { force: true });
execFileSync("zip", ["-qrX", zip, "import-hub-extension"], { cwd: tmp });
fs.rmSync(tmp, { recursive: true, force: true });
console.log("extension/reader.js and public/import-hub-extension.zip written");
